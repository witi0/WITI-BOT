const adjectives=new Set(['blue','red','purple','green','pink','black','white','yellow','golden','silver','tiny','big','small','crystal','infinite','autumn','summer','winter','spring','fluffy','flame']);
function displayGiftName(value){
 const original=String(value||'').trim();if(!original)return 'Regalo';
 const key=original.toLocaleLowerCase('en').replace(/[’]/g,"'").replace(/\s+/g,' ').trim();
 if(exact[key])return exact[key];
 const tokens=original.match(/[A-Za-z]+(?:['’][A-Za-z]+)?|[^A-Za-z]+/g)||[original];
 const alpha=tokens.filter(t=>/^[A-Za-z]/.test(t));
 const known=alpha.filter(t=>Object.hasOwn(words,t.toLowerCase()));
 if(!known.length)return original;
 if(alpha.length===2&&adjectives.has(alpha[0].toLowerCase())&&words[alpha[1].toLowerCase()]){
   const first=words[alpha[0].toLowerCase()],noun=words[alpha[1].toLowerCase()];
   if(['autumn','summer','winter','spring','crystal'].includes(alpha[0].toLowerCase()))return noun+' de '+first;
   return noun+' '+first;
 }
 let translated=tokens.map(t=>/^[A-Za-z]/.test(t)?(words[t.toLowerCase()]||t):t).join('');
 return translated.charAt(0).toLocaleUpperCase('es')+translated.slice(1);
}
